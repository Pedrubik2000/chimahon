/** Fsrs6 = py-fsrs 6.3.3 (no learning steps, no fuzz): rows from C:\dojo\code\tools\srs\fsrs_ref.py. */
class Fsrs6Test {
    /** params set, card, days since the previous rating, rating, R before, S, D, interval after. */
    private class Row(val p: Int, val c: Int, val days: Double, val rating: Int, val r: Double, val s: Double, val d: Double, val ivl: Int)

    @Test fun matchesPyFsrs() {
        val fsrs = listOf(Fsrs6(), Fsrs6(CUSTOM))
        var state: Fsrs6.State? = null
        var card = -1 to -1
        for ((i, row) in ROWS.withIndex()) {
            val f = fsrs[row.p]
            if (card != row.p to row.c) { card = row.p to row.c; state = null }
            val days = floor(row.days).toInt()
            val at = "row $i"
            state?.let { assertEquals(row.r, f.retrievability(days.toDouble(), it.stability), 1e-4, "$at R") }
            state = f.next(state, days, row.rating)
            assertEquals(row.s, state.stability, 1e-4, "$at S")
            assertEquals(row.d, state.difficulty, 1e-4, "$at D")
            assertEquals(row.ivl, f.interval(state.stability), "$at interval")
        }
    }

